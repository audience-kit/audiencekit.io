// Generates src/content/docs/api/graphql-reference.md from the schema dumps in the API bundle (scripts/bundle.mjs
// installs them in public/graphql/), so the reference never drifts from the API. It documents the staff view, the
// whole audience graph as staffql serves it, and marks what the consumer view leaves out; without a public staff
// view it documents the consumer view alone. Runs before dev and build, after the bundle.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
	buildSchema,
	isEnumType,
	isInputObjectType,
	isInterfaceType,
	isObjectType,
	isScalarType,
	isSpecifiedScalarType,
	isUnionType,
	getNamedType,
} from 'graphql';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '..');
const outPath = resolve(site, 'src/content/docs/api/graphql-reference.md');

const { views } = JSON.parse(readFileSync(resolve(site, 'src/bundle.json'), 'utf8')).main;
const view = (name) => views.find((v) => v.name === name);
const load = (v) => buildSchema(readFileSync(resolve(site, 'public', v.sdl), 'utf8'));
const documented = view('staff') ?? view('consumer');
const schema = load(documented);
// With the staff view documented, a field the consumer view doesn't have is marked "staffql only".
const consumer = documented.name === 'staff' && view('consumer') ? load(view('consumer')) : null;
const consumerHas = (typeName, fieldName) => {
	const type = consumer?.getType(typeName);
	return Boolean(type && 'getFields' in type && type.getFields()[fieldName]);
};
const STAFF_ONLY = ' <small>staffql only</small>';
const types = Object.values(schema.getTypeMap())
	.filter((t) => !t.name.startsWith('__') && !isSpecifiedScalarType(t))
	.sort((a, b) => a.name.localeCompare(b.name));

const slug = (name) => name.toLowerCase();
const link = (type) => {
	const named = getNamedType(type);
	return isSpecifiedScalarType(named) ? `\`${type}\`` : `[\`${type}\`](#${slug(named.name)})`;
};
// Collapse descriptions to one line so they fit in a table cell.
const oneLine = (text) =>
	(text ?? '').replace(/\s+/g, ' ').replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/>/g, '&gt;').trim();

function fieldTable(fields, { args = false, typeName = null } = {}) {
	const rows = Object.values(fields).map((f) => {
		let name = `\`${f.name}\``;
		if (consumer && typeName && !consumerHas(typeName, f.name)) name += STAFF_ONLY;
		if (args && f.args?.length) {
			name += `<br/>${f.args.map((a) => `\`${a.name}: ${a.type}\``).join('<br/>')}`;
		}
		return `| ${name} | ${link(f.type)} | ${oneLine(f.description)} |`;
	});
	return ['| Field | Type | Description |', '| --- | --- | --- |', ...rows].join('\n');
}

function section(type) {
	const out = [`### ${type.name}`, ''];
	let kind = 'Scalar';
	if (isObjectType(type)) kind = 'Object';
	if (isInterfaceType(type)) kind = 'Interface';
	if (isInputObjectType(type)) kind = 'Input';
	if (isEnumType(type)) kind = 'Enum';
	if (isUnionType(type)) kind = 'Union';
	const interfaces = isObjectType(type) ? type.getInterfaces().map((i) => link(i)) : [];
	const staffOnly = consumer && !consumer.getType(type.name) ? ' · staffql only' : '';
	out.push(`*${kind}*${interfaces.length ? ` · implements ${interfaces.join(', ')}` : ''}${staffOnly}`, '');
	if (type.description) out.push(oneLine(type.description), '');
	if (isObjectType(type) || isInterfaceType(type)) out.push(fieldTable(type.getFields(), { args: true, typeName: type.name }), '');
	if (isInputObjectType(type)) out.push(fieldTable(type.getFields(), { typeName: type.name }), '');
	if (isEnumType(type)) out.push(type.getValues().map((v) => `- \`${v.name}\` ${oneLine(v.description)}`).join('\n'), '');
	if (isUnionType(type)) out.push(type.getTypes().map((t) => `- ${link(t)}`).join('\n'), '');
	return out.join('\n');
}

const roots = [schema.getQueryType(), schema.getMutationType(), schema.getSubscriptionType()].filter(Boolean);
const rootNames = new Set(roots.map((t) => t.name));
const groups = [
	['Objects', types.filter((t) => isObjectType(t) && !rootNames.has(t.name) && !t.name.endsWith('Payload'))],
	['Mutation payloads', types.filter((t) => isObjectType(t) && t.name.endsWith('Payload'))],
	['Inputs', types.filter(isInputObjectType)],
	['Interfaces', types.filter(isInterfaceType)],
	['Enums', types.filter(isEnumType)],
	['Unions', types.filter(isUnionType)],
	['Scalars', types.filter((t) => isScalarType(t))],
].filter(([, list]) => list.length);

const md = [
	'---',
	'title: GraphQL reference',
	'description: Every query, mutation and type in the AudienceKit GraphQL schema.',
	'',
	'sidebar:',
	'  order: 4',
	'---',
	'',
	`<!-- Generated by scripts/graphql-reference.mjs from ${documented.sdl}. Do not edit by hand. -->`,
	'',
	consumer
		? 'This page is generated from the staff view\'s schema, the whole audience graph as `staffql` serves it. Fields and types marked *staffql only* aren\'t in the consumer view, the `graphql` endpoint the apps call (see [GraphQL](/api/graphql/#the-consumer-view-and-staffql)).'
		: 'This page is generated from the consumer view\'s schema, the audience graph as the `graphql` endpoint serves it to the apps.',
	`Download the dumps: ${views.map((v) => `[${v.name}](/${v.sdl}) ([introspection](/${v.introspection}))`).join(', ')}.`,
	'',
	...roots.flatMap((t) => [`## ${t.name}`, '', fieldTable(t.getFields(), { args: true, typeName: t.name }), '']),
	...groups.flatMap(([title, list]) => [`## ${title}`, '', ...list.map(section)]),
].join('\n');

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, md);
console.log(`graphql-reference: wrote ${types.length} types to ${outPath}`);
